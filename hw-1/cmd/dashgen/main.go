package main

import (
	"context"
	"fmt"
	"log/slog"
	"os"
	"os/signal"
	"syscall"
	"time"

	"ddia/hw1/internal/dashgen"
	"ddia/hw1/internal/env"
	"ddia/hw1/internal/grafana"
)

func main() {
	if err := run(); err != nil {
		slog.Error("dashgen failed", "err", err)
		os.Exit(1)
	}
}

func run() error {
	appURL := env.String("APP_URL", "http://app-dc1-1:8080")
	grafanaURL := env.String("GRAFANA_URL", "http://grafana:3000")
	datasourceUID := env.String("GRAFANA_DATASOURCE_UID", "victoriametrics")
	dashboardUID := env.String("DASHBOARD_UID", "")
	timeout, err := env.Duration("DASHGEN_TIMEOUT", 2*time.Minute)
	if err != nil {
		return err
	}
	token, err := env.SecretFile("GRAFANA_TOKEN_FILE")
	if err != nil {
		return err
	}

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()

	slog.Info("fetching handlers", "app", appURL)
	app, err := dashgen.FetchHandlers(ctx, appURL, 2*time.Second)
	if err != nil {
		return fmt.Errorf("fetch handlers: %w", err)
	}
	slog.Info("handlers discovered", "deployment", app.Deployment, "count", len(app.Handlers))

	if dashboardUID == "" {
		dashboardUID = app.Deployment
	}
	dash, err := dashgen.Build(dashgen.Spec{
		UID:           dashboardUID,
		Title:         app.Deployment,
		DatasourceUID: datasourceUID,
		Deployment:    app.Deployment,
		Handlers:      app.Handlers,
	})
	if err != nil {
		return fmt.Errorf("build dashboard: %w", err)
	}

	res, err := grafana.NewTokenAuth(grafanaURL, token).UpsertDashboard(ctx, dash, "generated by dashgen")
	if err != nil {
		return fmt.Errorf("upload dashboard: %w", err)
	}
	slog.Info("dashboard uploaded", "uid", res.UID, "version", res.Version, "url", grafanaURL+res.URL)

	return nil
}
